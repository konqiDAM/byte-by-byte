def harvest_from_lessons():
    """Pick up addresses that the lessons file explicitly calls closed / not worth another hour."""
    out = []
    if not os.path.exists(LESSONS):
        return out
    txt = io.open(LESSONS, encoding="utf-8", errors="replace").read()
    for m in re.finditer(r"do not spend|should not spend|closed for good|closed by the", txt, re.I):
        window = txt[max(0, m.start() - 1200): m.start() + 420]
        for a in set(re.findall(r"0x00[0-9a-f]{6}", window)):
            out.append((a, "lessons file marks this closed near: " + txt[m.start(): m.start() + 90]
                        .replace("\n", " ")))
    return out


def main():
    rows = dict()
    # 2026-11-13: this used to WRITE the file from SEED + lessons only, which silently deleted every entry that
    # exp91/close_*.py had appended (116 -> 31 walls lost, restored by hand). Existing entries win: this script only
    # ever adds. Anything removed here has to be removed from the file deliberately.
    if os.path.exists(CLOSED):
        for line in io.open(CLOSED, encoding="utf-8"):
            if "\t" in line:
                a, why = line.rstrip("\n").split("\t", 1)
                if a.strip():
                    rows[a.strip()] = why
    added = 0
    for a, why in SEED:
        if a not in rows:
            rows[a] = why
            added += 1
    for a, why in harvest_from_lessons():
        if a not in rows:
            rows[a] = why
            added += 1
    lines = "%s\n" % "\n".join("%s\t%s" % (a, rows[a]) for a in sorted(rows))
    io.open(CLOSED, "w", encoding="utf-8", newline="\n").write(lines)
    md = ["# CLOSED - do not spend an agent here", "",
          "Generated by `python exp91/closed_list.py`; machine copy `out/_closed.txt`.",
          "`INDEX.md` marks these CLOSED and `NEAR_MISSES.md` excludes them.", "",
          "| address | why it is closed |", "|---|---|"]
    for a in sorted(rows):
        md.append("| %s | %s |" % (a, rows[a]))
    io.open(MD, "w", encoding="utf-8", newline="\n").write("\n".join(md) + "\n")
    print("closed list: %d addresses -> out\\_closed.txt + CLOSED.md" % len(rows))


if __name__ == "__main__":
    main()
